// Writes the app's icon outlines (app/src/main/kotlin/.../ui/icons/KitIconData.kt) from the Windows app's
// src/Sonus/Controls/KitIcons.g.cs, which tools/kit-icons.mjs makes from the CreeperUX kit: each icon's strokes widened
// to 1.6 px and merged with its fills into one outline on a 24 px grid. Its path syntax ("F1 M12 10.4 C…") is Android's
// pathData once the fill rule prefix is dropped (F1 = non-zero, Android's default).
// Usage: node android/tools/kit-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const cs = readFileSync(join(repo, 'src/Sonus/Controls/KitIcons.g.cs'), 'utf8');
const icons = [...cs.matchAll(/\["([a-z0-9-]+)"\] = "F1 ([^"]+)"/g)].map(m => [m[1], m[2]]);
if (icons.length < 70) throw new Error(`only ${icons.length} icons found`);
const out = `// Generated by android/tools/kit-icons.mjs from src/Sonus/Controls/KitIcons.g.cs. Do not edit; run the tool.
package com.creeperux.sonus.ui.icons

/** The CreeperUX kit's icons as filled outlines on a 24 px grid (Android path data, non-zero fill). */
internal val KitIconData: Map<String, String> = mapOf(
${icons.map(([name, d]) => `    "${name}" to "${d}",`).join('\n')}
)
`;
writeFileSync(join(here, '../app/src/main/kotlin/com/creeperux/sonus/ui/icons/KitIconData.kt'), out);
console.log(`${icons.length} icons`);
