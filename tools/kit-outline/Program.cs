// kit-outline <icons.json> <KitIcons.g.cs>
// The kit's icons are 1.6 px round strokes (and a few fills) on a 24 px grid. XAML's own icon element, PathIcon, fills a
// geometry in the colour it inherits, so each icon is turned here, once, into the filled outline of what it draws: every
// stroke widened with Direct2D (round caps and joins, as the kit's CSS), the filled shapes added, all of it merged into one
// geometry, written as XAML path data. Input: { name: [ { kind: "p"|"r"|"c", data, fill }, ... ] } from tools/kit-icons.mjs.
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Text;
using System.Text.Json;

unsafe
{
    var icons = JsonSerializer.Deserialize<Dictionary<string, Part[]>>(File.ReadAllText(args[0]))!;
    var d2d = new D2D();
    var lines = new List<string>();
    foreach (var (name, parts) in icons.OrderBy(x => x.Key, StringComparer.Ordinal))
    {
        IntPtr shape = IntPtr.Zero;
        foreach (var part in parts)
        {
            var geometry = d2d.Geometry(part);
            var outline = d2d.Widen(geometry);
            shape = d2d.Union(shape, outline);
            if (part.fill) shape = d2d.Union(shape, geometry);
            else Marshal.Release(geometry);
        }
        lines.Add($"        [\"{name}\"] = \"{d2d.PathData(shape)}\",");
        Marshal.Release(shape);
    }
    File.WriteAllText(args[1], $$"""
        // Generated by tools/kit-icons.mjs (with tools/kit-outline) from the CreeperUX kit's icons, as foobar2k carries them:
        // each icon's strokes widened to 1.6 px with round caps and joins and merged with its fills into one outline on the
        // kit's 24 px grid, in XAML path syntax (PathIcon draws it). Do not edit; run the tool.
        namespace Sonus.Controls;

        public static class KitIcons
        {
            public static readonly IReadOnlyDictionary<string, string> All = new Dictionary<string, string>
            {
        {{string.Join("\n", lines)}}
            };
        }

        """);
    Console.WriteLine($"{lines.Count} icons outlined");
}

record Part(string kind, string data, bool fill);

[StructLayout(LayoutKind.Sequential)] struct Point { public float X, Y; public Point(double x, double y) { X = (float)x; Y = (float)y; } }
[StructLayout(LayoutKind.Sequential)] struct Bezier { public Point A, B, C; }
[StructLayout(LayoutKind.Sequential)] struct Arc { public Point End; public float Rx, Ry, Rotation; public int Sweep, Size; }
[StructLayout(LayoutKind.Sequential)] struct RoundedRect { public float Left, Top, Right, Bottom, Rx, Ry; }
[StructLayout(LayoutKind.Sequential)] struct EllipseShape { public Point Center; public float Rx, Ry; }
[StructLayout(LayoutKind.Sequential)] struct StrokeProps { public int StartCap, EndCap, DashCap, LineJoin; public float MiterLimit; public int DashStyle; public float DashOffset; }

/// <summary>The few Direct2D calls needed, through the COM vtables (d2d1.h's slot order).</summary>
unsafe sealed class D2D
{
    private const float Tolerance = 0.002f;
    private readonly IntPtr _factory, _stroke;

    [DllImport("d2d1.dll")] private static extern int D2D1CreateFactory(int type, Guid* riid, void* options, IntPtr* factory);

    public D2D()
    {
        var iid = new Guid("06152247-6f50-465a-9245-118bfd3b6007"); // ID2D1Factory
        IntPtr f;
        Check(D2D1CreateFactory(0, &iid, null, &f)); // single-threaded
        _factory = f;
        var props = new StrokeProps { StartCap = 2, EndCap = 2, DashCap = 2, LineJoin = 2, MiterLimit = 10 }; // round
        IntPtr s;
        Check(((delegate* unmanaged[Stdcall]<IntPtr, StrokeProps*, float*, uint, IntPtr*, int>)Slot(_factory, 11))(_factory, &props, null, 0, &s));
        _stroke = s;
    }

    private static IntPtr Slot(IntPtr com, int index) => (*(IntPtr**)com)[index];
    private static void Check(int hr) { if (hr < 0) Marshal.ThrowExceptionForHR(hr); }

    private (IntPtr Path, IntPtr Sink) NewPath()
    {
        IntPtr path, sink;
        Check(((delegate* unmanaged[Stdcall]<IntPtr, IntPtr*, int>)Slot(_factory, 10))(_factory, &path));    // CreatePathGeometry
        Check(((delegate* unmanaged[Stdcall]<IntPtr, IntPtr*, int>)Slot(path, 17))(path, &sink));             // Open
        ((delegate* unmanaged[Stdcall]<IntPtr, int, void>)Slot(sink, 3))(sink, 1);                            // SetFillMode(WINDING)
        return (path, sink);
    }

    private static void Close(IntPtr sink)
    {
        Check(((delegate* unmanaged[Stdcall]<IntPtr, int>)Slot(sink, 9))(sink));
        Marshal.Release(sink);
    }

    /// <summary>A part of an icon as a Direct2D geometry.</summary>
    public IntPtr Geometry(Part part)
    {
        var n = part.kind == "p" ? [] : part.data.Split(' ').Select(x => double.Parse(x, CultureInfo.InvariantCulture)).ToArray();
        IntPtr g;
        switch (part.kind)
        {
            case "r":
                var rect = new RoundedRect { Left = (float)n[0], Top = (float)n[1], Right = (float)(n[0] + n[2]), Bottom = (float)(n[1] + n[3]), Rx = (float)n[4], Ry = (float)n[4] };
                Check(((delegate* unmanaged[Stdcall]<IntPtr, RoundedRect*, IntPtr*, int>)Slot(_factory, 6))(_factory, &rect, &g));
                return g;
            case "c":
                var ellipse = new EllipseShape { Center = new Point(n[0], n[1]), Rx = (float)n[2], Ry = (float)n[2] };
                Check(((delegate* unmanaged[Stdcall]<IntPtr, EllipseShape*, IntPtr*, int>)Slot(_factory, 7))(_factory, &ellipse, &g));
                return g;
            default:
                var (path, sink) = NewPath();
                new SvgPath(sink, part.fill).Run(part.data);
                Close(sink);
                return path;
        }
    }

    /// <summary>The area a 1.6 px round stroke along <paramref name="geometry"/> covers.</summary>
    public IntPtr Widen(IntPtr geometry)
    {
        var (path, sink) = NewPath();
        Check(((delegate* unmanaged[Stdcall]<IntPtr, float, IntPtr, void*, float, IntPtr, int>)Slot(geometry, 16))(geometry, 1.6f, _stroke, null, Tolerance, sink));
        Close(sink);
        return path;
    }

    /// <summary>Both areas as one (Zero: nothing yet).</summary>
    public IntPtr Union(IntPtr a, IntPtr b)
    {
        if (a == IntPtr.Zero) { Marshal.AddRef(b); return b; }
        var (path, sink) = NewPath();
        Check(((delegate* unmanaged[Stdcall]<IntPtr, IntPtr, int, void*, float, IntPtr, int>)Slot(a, 11))(a, b, 0, null, Tolerance, sink)); // CombineWithGeometry(UNION)
        Close(sink);
        Marshal.Release(a);
        return path;
    }

    /// <summary>The geometry as XAML path data: Direct2D simplifies it to lines and cubic curves and hands them to a sink
    /// written here (a vtable of our own functions).</summary>
    public string PathData(IntPtr geometry)
    {
        Out.Clear();
        Out.Append("F1");
        var sink = OutputSink.Create();
        Check(((delegate* unmanaged[Stdcall]<IntPtr, int, void*, float, IntPtr, int>)Slot(geometry, 9))(geometry, 0, null, Tolerance, sink)); // Simplify(CUBICS_AND_LINES)
        return Out.ToString();
    }

    internal static readonly StringBuilder Out = new();
    internal static string N(float v) => Math.Round(v, 3).ToString("0.###", CultureInfo.InvariantCulture);
}

/// <summary>An ID2D1SimplifiedGeometrySink of our own, writing path data into D2D.Out. Lives for the whole run.</summary>
static unsafe class OutputSink
{
    private static IntPtr _object;

    public static IntPtr Create()
    {
        if (_object != IntPtr.Zero) return _object;
        var vtable = (IntPtr*)NativeMemory.Alloc(10, (nuint)sizeof(IntPtr));
        vtable[0] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, Guid*, IntPtr*, int>)&QueryInterface;
        vtable[1] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, uint>)&AddRef;
        vtable[2] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, uint>)&AddRef; // Release: it is never freed
        vtable[3] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, int, void>)&Ignore;  // SetFillMode
        vtable[4] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, int, void>)&Ignore;  // SetSegmentFlags
        vtable[5] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, Point, int, void>)&BeginFigure;
        vtable[6] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, Point*, uint, void>)&AddLines;
        vtable[7] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, Bezier*, uint, void>)&AddBeziers;
        vtable[8] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, int, void>)&EndFigure;
        vtable[9] = (IntPtr)(delegate* unmanaged[Stdcall]<IntPtr, int>)&Close;
        var obj = (IntPtr*)NativeMemory.Alloc(1, (nuint)sizeof(IntPtr));
        obj[0] = (IntPtr)vtable;
        return _object = (IntPtr)obj;
    }

    private static readonly Guid Unknown = new("00000000-0000-0000-C000-000000000046"), Simplified = new("2cd9069e-12e2-11dc-9fed-001143a055f9");

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]
    private static int QueryInterface(IntPtr self, Guid* iid, IntPtr* result)
    {
        if (*iid == Unknown || *iid == Simplified) { *result = self; return 0; }
        *result = IntPtr.Zero;
        return unchecked((int)0x80004002); // E_NOINTERFACE
    }

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])] private static uint AddRef(IntPtr self) => 1;
    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])] private static void Ignore(IntPtr self, int value) { }
    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])] private static int Close(IntPtr self) => 0;

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]
    private static void BeginFigure(IntPtr self, Point p, int begin) => D2D.Out.Append($" M{D2D.N(p.X)} {D2D.N(p.Y)}");

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]
    private static void AddLines(IntPtr self, Point* points, uint count)
    {
        for (int i = 0; i < count; i++) D2D.Out.Append($" L{D2D.N(points[i].X)} {D2D.N(points[i].Y)}");
    }

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]
    private static void AddBeziers(IntPtr self, Bezier* curves, uint count)
    {
        for (int i = 0; i < count; i++)
        {
            var c = curves[i];
            D2D.Out.Append($" C{D2D.N(c.A.X)} {D2D.N(c.A.Y)} {D2D.N(c.B.X)} {D2D.N(c.B.Y)} {D2D.N(c.C.X)} {D2D.N(c.C.Y)}");
        }
    }

    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]
    private static void EndFigure(IntPtr self, int end) { if (end == 1) D2D.Out.Append(" Z"); }
}

/// <summary>SVG path data (M L H V C S A Z, absolute and relative, as the kit uses) fed to a Direct2D geometry sink.</summary>
unsafe sealed class SvgPath(IntPtr sink, bool filled)
{
    private double _x, _y, _startX, _startY, _lastCx, _lastCy;
    private bool _open, _lastWasCurve;

    private static IntPtr Slot(int index, IntPtr com) => (*(IntPtr**)com)[index];

    private void Begin(double x, double y)
    {
        End(false);
        ((delegate* unmanaged[Stdcall]<IntPtr, Point, int, void>)Slot(5, sink))(sink, new Point(x, y), filled ? 0 : 1); // FILLED / HOLLOW
        _open = true; _startX = x; _startY = y;
    }

    private void End(bool closed)
    {
        if (!_open) return;
        ((delegate* unmanaged[Stdcall]<IntPtr, int, void>)Slot(8, sink))(sink, closed ? 1 : 0);
        _open = false;
    }

    private void Line(double x, double y) => ((delegate* unmanaged[Stdcall]<IntPtr, Point, void>)Slot(10, sink))(sink, new Point(x, y));

    private void Curve(double x1, double y1, double x2, double y2, double x, double y)
    {
        var b = new Bezier { A = new Point(x1, y1), B = new Point(x2, y2), C = new Point(x, y) };
        ((delegate* unmanaged[Stdcall]<IntPtr, Bezier*, void>)Slot(11, sink))(sink, &b);
    }

    private void ArcTo(double rx, double ry, double rotation, bool large, bool sweep, double x, double y)
    {
        var a = new Arc { End = new Point(x, y), Rx = (float)rx, Ry = (float)ry, Rotation = (float)rotation, Sweep = sweep ? 1 : 0, Size = large ? 1 : 0 };
        ((delegate* unmanaged[Stdcall]<IntPtr, Arc*, void>)Slot(14, sink))(sink, &a);
    }

    public void Run(string data)
    {
        var tokens = data.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        int i = 0;
        char command = 'M';
        double Next() => double.Parse(tokens[i++], CultureInfo.InvariantCulture);
        while (i < tokens.Length)
        {
            if (char.IsLetter(tokens[i][0])) command = tokens[i++][0];
            bool relative = char.IsLower(command);
            double ox = relative ? _x : 0, oy = relative ? _y : 0;
            if (!_open && char.ToUpperInvariant(command) is not ('M' or 'Z')) Begin(_x, _y); // drawing on after a Z: from its start
            bool curve = false;
            switch (char.ToUpperInvariant(command))
            {
                case 'M':
                    _x = ox + Next(); _y = oy + Next();
                    Begin(_x, _y);
                    command = relative ? 'l' : 'L'; // more pairs after a move are lines
                    break;
                case 'L': _x = ox + Next(); _y = oy + Next(); Line(_x, _y); break;
                case 'H': _x = (relative ? _x : 0) + Next(); Line(_x, _y); break;
                case 'V': _y = (relative ? _y : 0) + Next(); Line(_x, _y); break;
                case 'C':
                {
                    double x1 = ox + Next(), y1 = oy + Next(), x2 = ox + Next(), y2 = oy + Next();
                    _x = ox + Next(); _y = oy + Next();
                    Curve(x1, y1, x2, y2, _x, _y);
                    _lastCx = x2; _lastCy = y2; curve = true;
                    break;
                }
                case 'S':
                {
                    // the first control point mirrors the previous curve's second one
                    double x1 = _lastWasCurve ? 2 * _x - _lastCx : _x, y1 = _lastWasCurve ? 2 * _y - _lastCy : _y;
                    double x2 = ox + Next(), y2 = oy + Next();
                    _x = ox + Next(); _y = oy + Next();
                    Curve(x1, y1, x2, y2, _x, _y);
                    _lastCx = x2; _lastCy = y2; curve = true;
                    break;
                }
                case 'A':
                {
                    double rx = Next(), ry = Next(), rotation = Next();
                    bool large = Next() != 0, sweep = Next() != 0;
                    _x = ox + Next(); _y = oy + Next();
                    ArcTo(rx, ry, rotation, large, sweep, _x, _y);
                    break;
                }
                case 'Z':
                    End(true);
                    _x = _startX; _y = _startY;
                    break;
                default: throw new FormatException($"path command {command} is not supported: {data}");
            }
            _lastWasCurve = curve;
        }
        End(false);
    }
}
